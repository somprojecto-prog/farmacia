let IDIOMA_ATUAL = 'pt';
try { const c = localStorage.getItem('site_idioma'); if (c && I18N[c]) IDIOMA_ATUAL = c; } catch(e){}

function t(chave){ return (I18N[IDIOMA_ATUAL] && I18N[IDIOMA_ATUAL][chave]) || I18N.pt[chave] || chave; }

function aplicarIdioma(lang){
  if (!I18N[lang]) lang = 'pt';
  IDIOMA_ATUAL = lang;
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-html]').forEach(el => { el.innerHTML = t(el.dataset.i18nHtml); });
}

// Chamada pelo common.js com o idioma guardado pelo gestor na base de dados
function aplicarIdiomaDe(lang){
  if (!lang || !I18N[lang]) lang = 'pt';
  try { localStorage.setItem('site_idioma', lang); } catch(e){}
  if (lang !== IDIOMA_ATUAL) {
    aplicarIdioma(lang);
    if (typeof carregarDestaques === 'function') carregarDestaques();
  }
}

// Aplica já o idioma guardado no browser (evita "piscar"); o resto é confirmado pelo common.js
document.addEventListener('DOMContentLoaded', () => aplicarIdioma(IDIOMA_ATUAL));
